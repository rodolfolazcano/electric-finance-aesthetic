/** Divide la base en chunks indexables (por sección y por ítem). Tolera encabezados
 *  con o sin prefijo "##" y subsecciones de texto (no ítems numerados). */
function chunkear(texto: string): string[] {
  const lineas = texto.split(/\r?\n/);
  const chunks: string[] = [];
  let titulo = "";
  const esItem = /^\d+\.\s+/;
  const esTitulo = /^[A-ZÀ-Ý][A-Za-zÀ-ÿÁÉÍÓÚÑ0-9 -]+$/;
  for (const linea of lineas) {
    const l = linea.trim();
    if (!l) continue;
    const mHash = l.match(/^#{1,2}\s+(.+)$/);
    if (mHash) {
      titulo = mHash[1]!.trim();
      continue;
    }
    if (esItem.test(l)) {
      const textoItem = l.replace(/^\d+\.\s*/, "").trim();
      chunks.push(`${titulo}: ${textoItem}`.trim());
      continue;
    }
    if (esTitulo.test(l)) {
      titulo = l;
    }
  }
  return chunks.filter(Boolean);
}

