/** Busca los chunks más relevantes por similitud coseno. Si los embeddings fallan, cae a coincidencia por palabras. */
export async function buscarEnBase(
  query: string,
  topK = 4,
): Promise<Array<{ texto: string; similitud: number }>> {
  const q = query.toLowerCase();
  try {
    const qv = normalizar(await generarEmbedding(query));
    const chunks = await obtenerChunksEmbeddizados();
    const scored = chunks
      .map((c) => ({ texto: c.chunk, similitud: coseno(qv, c.vector) }))
      .sort((a, b) => b.similitud - a.similitud)
      .slice(0, topK);
    if (scored.some((s) => s.similitud > 0.25)) return scored;
  } catch {
    /* caer al fallback */
  }
  const terms = q
    .split(/\s+/)
    .filter((t) => t.length > 2)
    .filter(
      (t) =>
        !/^(qué|que|el|la|los|las|con|por|para|una|uno|saber|quiere|como|cómo|cuál|cual|es|son|hay|debería|puedo)$/.test(
          t,
        ),
    );
  return KNOWLEDGE_CHUNKS.map((texto) => {
    const t = texto.toLowerCase();
    const coincidencias = terms.reduce((n, term) => n + (t.includes(term) ? 1 : 0), 0);
    return { texto, similitud: coincidencias / Math.max(1, terms.length) };
  })
    .filter((r) => r.similitud > 0)
    .sort((a, b) => b.similitud - a.similitud)
    .slice(0, topK);
}

